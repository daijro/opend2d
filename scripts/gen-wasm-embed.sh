#!/usr/bin/env bash
# Regenerate the wasm32 embed tables (wasm has no filesystem): the conformance corpus and the ratchet
# baked from the conformance suite (the conformance/suite submodule), plus the fonts. One
# `(name, scene.json, oracle.json, oracle.bgra)` tuple per scene that has scene+oracle JSON;
# `oracle.bgra` is `b""` when the scene wrote no pixels (EndDraw failed, e.g. cms2-04/05), matching the
# native runner. The suite data is baked by ABSOLUTE include paths (like the fonts), so nothing from
# the suite is committed into opend2d: corpus.rs / passing.txt are committed EMPTY and this script
# overwrites them locally — never commit the populated form. The suite is absent ⇒ empty tables ⇒ wasm
# skips every scene (public-clone mode). Run after adding/removing scenes.
set -euo pipefail
cd "$(dirname "$0")/.."
export LC_ALL=C # glob in byte order, the order the native runner reads scenes in (the digest is order-dependent)

out=crates/d2d/tests/embed/corpus.rs
pout=crates/d2d/tests/embed/passing.txt
mkdir -p "$(dirname "$out")"

# Resolve the suite the same way d2d_reference::suite_dir() does: the D2D_SUITE override, else the
# in-tree submodule, else the main checkout's copy. Absolutise it for the baked include paths.
suite=""
for cand in "${D2D_SUITE:-}" conformance/suite "$(dirname "$(git rev-parse --path-format=absolute --git-common-dir)")/conformance/suite"; do
  if [ -n "$cand" ] && [ -d "$cand/scenes" ]; then suite=$(cd "$cand" && pwd); break; fi
done

{
  echo "// @generated by scripts/gen-wasm-embed.sh — do NOT commit the populated form (absolute paths)."
  echo "&["
  if [ -n "$suite" ]; then
    # Sort extensionless names, as cases() does: "scene" precedes "scene-q0".
    while IFS= read -r name; do
      oj="$suite/oracle/win11-26100/$name.json"
      case "$name" in environment|failures|shader*) continue;; esac # not conformance scenes (see cases())
      [ -f "$suite/scenes/$name.json" ] || continue
      if [ -f "$suite/oracle/win11-26100/$name.bgra" ]; then
        bgra="include_bytes!(\"$suite/oracle/win11-26100/$name.bgra\")"
      else
        bgra='b""' # EndDraw failed → no pixels, same as the native runner's empty bgra
      fi
      printf '    ("%s", include_str!("%s/scenes/%s.json"), include_str!("%s/oracle/win11-26100/%s.json"), %s),\n' \
        "$name" "$suite" "$name" "$suite" "$name" "$bgra"
    done < <(for oj in "$suite"/oracle/win11-26100/*.json; do
      name=${oj##*/}; printf '%s\n' "${name%.json}"
    done | sort)
  fi
  echo "]"
} > "$out"
echo "wrote $out ($(grep -c '^    (' "$out" || true) scenes from ${suite:-<none>})"

# embed/passing.txt: the suite's ratchet for the wasm build (committed empty; populated locally only).
if [ -n "$suite" ] && [ -f "$suite/passing.txt" ]; then cp "$suite/passing.txt" "$pout"; else : > "$pout"; fi
echo "wrote $pout ($(wc -l < "$pout") passing lines)"

# embed/fonts.rs: the fonts the corpus uses, baked into the wasm build (wasm has no filesystem, and
# the native fonts_dir() git-derivation does not run there). Fonts live in the gitignored, shared
# ref/windows/Fonts; include_bytes! them by absolute path so nothing font-related is committed. When
# ref/ is absent the table is empty and wasm text scenes skip — exactly as on native without fonts.
fout=crates/d2d/tests/embed/fonts.rs
fdir=${D2D_FONTS:-}
if [ -z "$fdir" ]; then
  fdir=$(git rev-parse --path-format=absolute --git-common-dir 2>/dev/null) &&
    fdir=$(dirname "$fdir")/ref/windows/Fonts || fdir=""
fi
if [ -d "$fdir" ]; then fdir=$(cd "$fdir" && pwd); fi
{
  echo "// @generated by scripts/gen-wasm-embed.sh — do NOT commit the populated form (absolute paths)."
  echo "&["
  if [ -n "$fdir" ] && [ -d "$fdir" ]; then
    # Embed EVERY font file in ref/windows/Fonts, keyed by basename, so the wasm corpus can never drift
    # from the fonts conformance.rs resolves (font_file()/fallback_face()) — a hard-coded subset once
    # dropped impact.ttf/georgiai.ttf/Nirmala.ttc and broke the 4A parity digest. Sorted in byte order
    # (LC_ALL=C) for a deterministic table.
    while IFS= read -r path; do
      f=$(basename "$path")
      printf '    ("%s", include_bytes!("%s/%s")),\n' "$f" "$fdir" "$f"
    done < <(find "$fdir" -maxdepth 1 -type f \( -iname '*.ttf' -o -iname '*.ttc' -o -iname '*.otf' \) | LC_ALL=C sort)
  fi
  echo "]"
} > "$fout"
echo "wrote $fout ($(grep -c include_bytes "$fout") fonts from ${fdir:-<none>})"
