/// Store linear RGB to sRGB8, then decode for a subsequent texture sample.
pub(crate) fn roundtrip(v: f32) -> f32 {
    // WARP's float→sRGB8 store: clamp, multiply by 4095, round to nearest even, then table lookup.
    let index = (v.clamp(0.0, 1.0) * 4095.0).round_ties_even() as u16;
    let code = ENCODE_START.partition_point(|&start| start <= index);
    f32::from_bits(DECODE[code])
}

